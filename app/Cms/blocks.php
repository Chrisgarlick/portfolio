<?php

declare(strict_types=1);

use Cg\Cms\Schema\Block;
use Cg\Cms\Schema\Field;

/*
|------------------------------------------------------------------------------
| The site's own blocks: kit's website sections, and two of the site's own
|------------------------------------------------------------------------------
|
| kit-blocks/ is generated by `kit build-cgcms` (run `make sync`; never edit
| it by hand). Loading kit-blocks.php also loads kit's runtime and registers
| the `kit-blocks::` views. cg-cms's registry adds these to its built-ins, so
| pages still holding the old built-in blocks keep rendering; app/Cms/schema.php
| decides which blocks an editor may add (the kit ones).
|
| The `site-*` blocks put the site's working forms between kit's sections:
| the free site audit (its tool, unchanged) and the privacy page's "delete
| your data" request. Their copy is editable; what they do is not.
|
*/

return [
    ...require base_path('kit-blocks/kit-blocks.php'),

    Block::make('site-audit-tool', 'Site audit tool')->fields([
        Field::text('label')->label('Label above the address')->maxLength(60)->default('Your website address'),
        Field::text('number')->label('Number before the label')->maxLength(8)->help('Like "01". Decoration: screen readers skip it.'),
        Field::text('placeholder')->label('Example address')->maxLength(60)->default('your-website.co.uk'),
        Field::text('button')->label('Button')->maxLength(30)->default('Check my site'),
        Field::text('note')->label('Note under the address')->maxLength(120),
    ])->view('blocks.site-audit-tool'),

    Block::make('site-data-deletion', 'Delete your data form')->fields([
        Field::text('label')->label('Label')->maxLength(60)->default('Your email address'),
        Field::text('placeholder')->label('Example address')->maxLength(60)->default('you@your-website.co.uk'),
        Field::text('button')->label('Button')->maxLength(30)->default('Send the link'),
        Field::text('note')->label('Note under the form')->maxLength(120)->default('The link works for 24 hours.'),
    ])->view('blocks.site-data-deletion'),
];
